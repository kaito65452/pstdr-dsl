use crate::ast::*;
use crate::spec::{map_item_property, map_method, map_property, map_world_method};
use crate::validator::eval_static_string;
use std::collections::{BTreeSet, HashMap, HashSet};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EmitMode {
    JavaScript,
    TypeScript,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ComponentKind {
    Item,
    Block,
}

#[derive(Debug, Clone)]
pub struct CodegenOptions {
    pub source_file: String,
    pub source_map_comments: bool,
    pub custom_components: Vec<(String, ComponentKind)>,
    pub bound_block_ids: Vec<String>,
}

#[derive(Debug, Clone, Default)]
pub struct SharedContext {
    pub shared_exports: HashSet<String>,
    pub shared_muts: HashSet<String>,
    pub shared_states: HashSet<String>,
    pub shared_import_path: Option<String>,
}

impl SharedContext {
    pub fn from_shared_items(shared: &[TopLevelItem], import_path: Option<String>) -> Self {
        let mut ctx = Self {
            shared_exports: HashSet::new(),
            shared_muts: HashSet::new(),
            shared_states: HashSet::new(),
            shared_import_path: import_path,
        };
        for item in shared {
            match item {
                TopLevelItem::ConstDecl(d) => {
                    ctx.shared_exports.insert(d.name.clone());
                }
                TopLevelItem::MutDecl(d) => {
                    ctx.shared_muts.insert(d.name.clone());
                }
                TopLevelItem::StateDecl(s) => {
                    ctx.shared_states.insert(s.name.clone());
                }
                TopLevelItem::FuncDecl(f) => {
                    ctx.shared_exports.insert(f.name.clone());
                }
                TopLevelItem::UnsafeFuncDecl(f) => {
                    ctx.shared_exports.insert(f.name.clone());
                }
                TopLevelItem::UnsafeVarDecl(u) => {
                    ctx.shared_exports.insert(u.name.clone());
                }
                _ => {}
            }
        }
        ctx
    }
}

pub fn emit_code(program: &Program, opts: &CodegenOptions, mode: EmitMode) -> String {
    let mut state_names = HashSet::new();
    let mut const_strings = HashMap::new();
    for item in &program.items {
        match item {
            TopLevelItem::StateDecl(s) => {
                state_names.insert(s.name.clone());
            }
            TopLevelItem::ConstDecl(d) => {
                if let Some(s) = eval_static_string(&d.value, &const_strings) {
                    const_strings.insert(d.name.clone(), s);
                }
            }
            _ => {}
        }
    }

    let mut cg = Codegen {
        opts,
        mode,
        state_names,
        const_strings,
        shared: SharedContext::default(),
        used_shared_imports: BTreeSet::new(),
        local_scopes: Vec::new(),
        emit_source_lines: false,
        needs_world: false,
        needs_system: false,
        needs_equipment_slot: false,
        needs_in_helper: false,
        needs_within_helper: false,
        in_before_event: false,
        block_interact_callbacks: Vec::new(),
        block_tick_callbacks: Vec::new(),
        body: String::new(),
        indent: 0,
    };

    cg.emit_program(program);

    let default_spec = crate::spec::BedrockSpec::bundled();
    let target_ver = program
        .header
        .as_ref()
        .map(|h| h.target.as_str())
        .unwrap_or(&default_spec.bedrock_version);

    let mut out = String::new();
    if opts.source_map_comments {
        out.push_str(&format!(
            "// Generated by pstdr-c v0.1.0-alpha from {} (Bedrock {})\n",
            opts.source_file, target_ver
        ));
    }

    let api_ver = program
        .header
        .as_ref()
        .map(|h| h.api.as_str())
        .unwrap_or(&default_spec.script_api_version);
    let api_major: u64 = api_ver
        .split('.')
        .next()
        .and_then(|s| s.parse().ok())
        .unwrap_or(2);
    let use_v2_startup =
        api_major >= 2 && crate::wiring::uses_custom_components_v2(target_ver);

    let has_components = !opts.custom_components.is_empty();
    let need_world = cg.needs_world || (has_components && !use_v2_startup);
    let need_system = cg.needs_system || (has_components && use_v2_startup);

    let mut imports = Vec::new();
    if need_world {
        imports.push("world");
    }
    if need_system {
        imports.push("system");
    }
    if cg.needs_equipment_slot {
        imports.push("EquipmentSlot");
    }
    if !imports.is_empty() {
        out.push_str(&format!(
            "import {{ {} }} from \"@minecraft/server\";\n\n",
            imports.join(", ")
        ));
    }

    if has_components {
        let init_ev_param = if mode == EmitMode::TypeScript {
            "(initEv: any)"
        } else {
            "(initEv)"
        };
        let cb_ev_param = if mode == EmitMode::TypeScript {
            "(ev: any)"
        } else {
            "(ev)"
        };
        if !use_v2_startup {
            out.push_str(&format!(
                "world.beforeEvents.worldInitialize.subscribe({init_ev_param} => {{\n"
            ));
        } else {
            out.push_str(&format!(
                "system.beforeEvents.startup.subscribe({init_ev_param} => {{\n"
            ));
        }
        for (comp_id, kind) in &opts.custom_components {
            match kind {
                ComponentKind::Item => {
                    out.push_str(&format!(
                        "    initEv.itemComponentRegistry.registerCustomComponent(\"{comp_id}\", {{}});\n"
                    ));
                }
                ComponentKind::Block => {
                    let has_interact = !cg.block_interact_callbacks.is_empty();
                    let has_tick = !cg.block_tick_callbacks.is_empty();
                    if !has_interact && !has_tick {
                        out.push_str(&format!(
                            "    initEv.blockComponentRegistry.registerCustomComponent(\"{comp_id}\", {{}});\n"
                        ));
                    } else {
                        out.push_str(&format!(
                            "    initEv.blockComponentRegistry.registerCustomComponent(\"{comp_id}\", {{\n"
                        ));
                        let mut methods = Vec::new();
                        if has_interact {
                            let mut m = format!("        onPlayerInteract{cb_ev_param} {{\n");
                            for snippet in &cg.block_interact_callbacks {
                                m.push_str(snippet);
                            }
                            m.push_str("        }");
                            methods.push(m);
                        }
                        if has_tick {
                            let mut m = format!("        onTick{cb_ev_param} {{\n");
                            for snippet in &cg.block_tick_callbacks {
                                m.push_str(snippet);
                            }
                            m.push_str("        }");
                            methods.push(m);
                        }
                        out.push_str(&methods.join(",\n"));
                        out.push_str("\n    });\n");
                    }
                }
            }
        }
        out.push_str("});\n\n");
    }

    if cg.needs_in_helper {
        if mode == EmitMode::TypeScript {
            out.push_str("function __pstdr_in(item: any, container: any): boolean {\n");
        } else {
            out.push_str("function __pstdr_in(item, container) {\n");
        }
        out.push_str(
            "    if (Array.isArray(container) || typeof container === \"string\") return container.includes(item);\n\
             \x20   if (container && typeof container === \"object\") return item in container;\n\
             \x20   return false;\n}\n\n",
        );
    }

    if cg.needs_within_helper {
        if mode == EmitMode::TypeScript {
            out.push_str("function __pstdr_within(a: any, b: any): boolean {\n");
        } else {
            out.push_str("function __pstdr_within(a, b) {\n");
        }
        out.push_str(
            "    if (!a || !b || !a.location || !b.location) return false;\n\
             \x20   return Math.hypot(a.location.x - b.location.x, a.location.y - b.location.y, a.location.z - b.location.z) <= 5;\n}\n\n",
        );
    }

    out.push_str(&cg.body);
    out
}

fn assemble_partitioned_module(
    cg: &Codegen<'_>,
    header: Option<&AddonDirective>,
    mode: EmitMode,
) -> String {
    let default_spec = crate::spec::BedrockSpec::bundled();
    let target_ver = header
        .map(|h| h.target.as_str())
        .unwrap_or(&default_spec.bedrock_version);

    let mut out = String::new();
    if cg.opts.source_map_comments {
        out.push_str(&format!(
            "// Generated by pstdr-c v0.1.0-alpha from {} (Bedrock {})\n",
            cg.opts.source_file, target_ver
        ));
    }

    let mut mc_imports = Vec::new();
    if cg.needs_world {
        mc_imports.push("world");
    }
    if cg.needs_system {
        mc_imports.push("system");
    }
    if cg.needs_equipment_slot {
        mc_imports.push("EquipmentSlot");
    }
    let has_mc_imports = !mc_imports.is_empty();
    if has_mc_imports {
        out.push_str(&format!(
            "import {{ {} }} from \"@minecraft/server\";\n",
            mc_imports.join(", ")
        ));
    }

    let has_shared_imports = !cg.used_shared_imports.is_empty() && cg.shared.shared_import_path.is_some();
    if has_shared_imports {
        let path = cg.shared.shared_import_path.as_deref().unwrap_or("");
        let names: Vec<&str> = cg.used_shared_imports.iter().map(|s| s.as_str()).collect();
        out.push_str(&format!(
            "import {{ {} }} from \"{path}\";\n",
            names.join(", ")
        ));
    }

    if has_mc_imports || has_shared_imports || cg.opts.source_map_comments {
        out.push('\n');
    }

    if cg.needs_in_helper {
        if mode == EmitMode::TypeScript {
            out.push_str("function __pstdr_in(item: any, container: any): boolean {\n");
        } else {
            out.push_str("function __pstdr_in(item, container) {\n");
        }
        out.push_str(
            "    if (Array.isArray(container) || typeof container === \"string\") return container.includes(item);\n\
             \x20   if (container && typeof container === \"object\") return item in container;\n\
             \x20   return false;\n}\n\n",
        );
    }

    if cg.needs_within_helper {
        if mode == EmitMode::TypeScript {
            out.push_str("function __pstdr_within(a: any, b: any): boolean {\n");
        } else {
            out.push_str("function __pstdr_within(a, b) {\n");
        }
        out.push_str(
            "    if (!a || !b || !a.location || !b.location) return false;\n\
             \x20   return Math.hypot(a.location.x - b.location.x, a.location.y - b.location.y, a.location.z - b.location.z) <= 5;\n}\n\n",
        );
    }

    out.push_str(&cg.body);
    out
}

/// Emits `_shared/<stem>.shared.js` (or `.ts`) containing exported `const`, `state`, `func`,
/// `unsafe` declarations, and top-level `mut` variables wrapped in `export const __pstdr_mut = { ... };`.
pub fn emit_shared_module(
    shared_items: &[TopLevelItem],
    header: Option<&AddonDirective>,
    source_file: &str,
    source_map_comments: bool,
    mode: EmitMode,
) -> String {
    let opts = CodegenOptions {
        source_file: source_file.to_string(),
        source_map_comments,
        custom_components: Vec::new(),
        bound_block_ids: Vec::new(),
    };
    let shared_ctx = SharedContext::from_shared_items(shared_items, None);
    let state_names = shared_ctx.shared_states.clone();

    let mut cg = Codegen {
        opts: &opts,
        mode,
        state_names,
        const_strings: HashMap::new(),
        shared: shared_ctx,
        used_shared_imports: BTreeSet::new(),
        local_scopes: Vec::new(),
        emit_source_lines: true,
        needs_world: false,
        needs_system: false,
        needs_equipment_slot: false,
        needs_in_helper: false,
        needs_within_helper: false,
        in_before_event: false,
        block_interact_callbacks: Vec::new(),
        block_tick_callbacks: Vec::new(),
        body: String::new(),
        indent: 0,
    };

    let mut consts = Vec::new();
    let mut muts = Vec::new();
    let mut others = Vec::new();
    for item in shared_items {
        match item {
            TopLevelItem::ConstDecl(d) => consts.push(d),
            TopLevelItem::MutDecl(d) => muts.push(d),
            _ => others.push(item),
        }
    }

    let mut first_section = true;
    for d in consts {
        if !first_section {
            cg.body.push('\n');
        }
        first_section = false;
        cg.emit_source_comment(d.span.line);
        let val = cg.emit_expr(&d.value);
        cg.line(&format!("export const {} = {val};", d.name));
    }

    if !muts.is_empty() {
        if !first_section {
            cg.body.push('\n');
        }
        first_section = false;
        cg.emit_source_comment(muts[0].span.line);
        if mode == EmitMode::TypeScript {
            cg.line("export const __pstdr_mut: Record<string, any> = {");
        } else {
            cg.line("export const __pstdr_mut = {");
        }
        cg.indent += 1;
        for (idx, d) in muts.iter().enumerate() {
            let val = cg.emit_expr(&d.value);
            let comma = if idx + 1 < muts.len() { "," } else { "" };
            cg.line(&format!("{}: {val}{comma}", d.name));
        }
        cg.indent -= 1;
        cg.line("};");
    }

    for item in others {
        if !first_section {
            cg.body.push('\n');
        }
        first_section = false;
        match item {
            TopLevelItem::StateDecl(s) => {
                cg.emit_source_comment(s.span.line);
                let default_js = cg.emit_expr(&s.default_value);
                let key = format!("pstdr:{}", s.name);
                if mode == EmitMode::TypeScript {
                    cg.line(&format!(
                        "export function __get_{}(owner: any) {{ const v = owner.getDynamicProperty(\"{key}\"); return v !== undefined ? v : ({default_js}); }}",
                        s.name
                    ));
                    cg.line(&format!(
                        "export function __set_{}(owner: any, value: any): void {{ owner.setDynamicProperty(\"{key}\", value); }}",
                        s.name
                    ));
                } else {
                    cg.line(&format!(
                        "export function __get_{}(owner) {{ const v = owner.getDynamicProperty(\"{key}\"); return v !== undefined ? v : ({default_js}); }}",
                        s.name
                    ));
                    cg.line(&format!(
                        "export function __set_{}(owner, value) {{ owner.setDynamicProperty(\"{key}\", value); }}",
                        s.name
                    ));
                }
            }
            TopLevelItem::FuncDecl(f) => {
                cg.emit_source_comment(f.span.line);
                let params: Vec<String> = f
                    .params
                    .iter()
                    .map(|(p, _)| {
                        if mode == EmitMode::TypeScript {
                            format!("{p}: any")
                        } else {
                            p.clone()
                        }
                    })
                    .collect();
                cg.line(&format!("export function {}({}) {{", f.name, params.join(", ")));
                cg.push_scope();
                for (p, _) in &f.params {
                    cg.bind_local(p);
                }
                cg.indent += 1;
                cg.emit_block_stmts(&f.body.stmts);
                cg.indent -= 1;
                cg.pop_scope();
                cg.line("}");
            }
            TopLevelItem::UnsafeFuncDecl(f) => {
                cg.emit_source_comment(f.span.line);
                cg.line(&format!(
                    "// [unsafe:{} @ {}:{}]",
                    f.name, opts.source_file, f.span.line
                ));
                let params: Vec<String> = f
                    .params
                    .iter()
                    .map(|p| {
                        if mode == EmitMode::TypeScript {
                            format!("{p}: any")
                        } else {
                            p.clone()
                        }
                    })
                    .collect();
                cg.line(&format!(
                    "export function {}({}) {{{}}}",
                    f.name,
                    params.join(", "),
                    f.raw_body
                ));
            }
            TopLevelItem::UnsafeVarDecl(u) => {
                cg.emit_source_comment(u.span.line);
                cg.line(&format!(
                    "// [unsafe:{} @ {}:{}]",
                    u.name, opts.source_file, u.span.line
                ));
                let mut rest = u.raw_rest.trim_end().to_string();
                if !rest.ends_with(';') {
                    rest.push(';');
                }
                cg.line(&format!("export {} {}", u.keyword, rest));
            }
            _ => {}
        }
    }

    assemble_partitioned_module(&cg, header, mode)
}

/// Emits `items/<slug>.js` (or `.ts`) merging `on hit`, `on right click`, and `on consume`
/// handlers for a single registered custom item into `export const component = { ... };`.
pub fn emit_item_component_module(
    handlers: &[EventHandler],
    shared: &SharedContext,
    header: Option<&AddonDirective>,
    source_file: &str,
    source_map_comments: bool,
    mode: EmitMode,
) -> String {
    let opts = CodegenOptions {
        source_file: source_file.to_string(),
        source_map_comments,
        custom_components: Vec::new(),
        bound_block_ids: Vec::new(),
    };
    let mut cg = Codegen {
        opts: &opts,
        mode,
        state_names: shared.shared_states.clone(),
        const_strings: HashMap::new(),
        shared: shared.clone(),
        used_shared_imports: BTreeSet::new(),
        local_scopes: Vec::new(),
        emit_source_lines: true,
        needs_world: false,
        needs_system: false,
        needs_equipment_slot: false,
        needs_in_helper: false,
        needs_within_helper: false,
        in_before_event: false,
        block_interact_callbacks: Vec::new(),
        block_tick_callbacks: Vec::new(),
        body: String::new(),
        indent: 0,
    };

    let mut on_use = Vec::new();
    let mut on_hit = Vec::new();
    let mut on_consume = Vec::new();
    for ev in handlers {
        match &ev.kind {
            EventKind::RightClick { .. } => on_use.push(ev),
            EventKind::HitTarget { .. } => on_hit.push(ev),
            EventKind::Consume { .. } => on_consume.push(ev),
            _ => {}
        }
    }

    let ev_param = if mode == EmitMode::TypeScript {
        "(ev: any)"
    } else {
        "(ev)"
    };
    let mut methods = Vec::new();

    if !on_use.is_empty() {
        let wrap = on_use.len() > 1;
        let snippet = cg.emit_to_buffer(2, |c| {
            for ev in &on_use {
                if let EventKind::RightClick { actor_var, .. } = &ev.kind {
                    if wrap {
                        c.line("{");
                        c.indent += 1;
                    }
                    c.emit_source_comment(ev.span.line);
                    c.push_scope();
                    c.bind_local(actor_var);
                    c.line(&format!("const {actor_var} = ev.source;"));
                    c.emit_block_stmts(&ev.body.stmts);
                    c.pop_scope();
                    if wrap {
                        c.indent -= 1;
                        c.line("}");
                    }
                }
            }
        });
        methods.push(format!("    onUse{ev_param} {{\n{snippet}    }}"));
    }

    if !on_hit.is_empty() {
        let wrap = on_hit.len() > 1;
        let snippet = cg.emit_to_buffer(2, |c| {
            for ev in &on_hit {
                if let EventKind::HitTarget {
                    target_var,
                    actor_var,
                    ..
                } = &ev.kind
                {
                    if wrap {
                        c.line("{");
                        c.indent += 1;
                    }
                    c.emit_source_comment(ev.span.line);
                    c.push_scope();
                    c.bind_local(actor_var);
                    c.bind_local(target_var);
                    c.line(&format!("const {actor_var} = ev.attackingEntity;"));
                    c.line(&format!("const {target_var} = ev.hitEntity;"));
                    c.emit_block_stmts(&ev.body.stmts);
                    c.pop_scope();
                    if wrap {
                        c.indent -= 1;
                        c.line("}");
                    }
                }
            }
        });
        methods.push(format!("    onHitEntity{ev_param} {{\n{snippet}    }}"));
    }

    if !on_consume.is_empty() {
        let wrap = on_consume.len() > 1;
        let snippet = cg.emit_to_buffer(2, |c| {
            for ev in &on_consume {
                if let EventKind::Consume { actor_var, .. } = &ev.kind {
                    if wrap {
                        c.line("{");
                        c.indent += 1;
                    }
                    c.emit_source_comment(ev.span.line);
                    c.push_scope();
                    c.bind_local(actor_var);
                    c.line(&format!("const {actor_var} = ev.source;"));
                    c.emit_block_stmts(&ev.body.stmts);
                    c.pop_scope();
                    if wrap {
                        c.indent -= 1;
                        c.line("}");
                    }
                }
            }
        });
        methods.push(format!("    onConsume{ev_param} {{\n{snippet}    }}"));
    }

    if methods.is_empty() {
        cg.line("export const component = {};");
    } else {
        cg.line("export const component = {");
        cg.body.push_str(&methods.join(",\n"));
        cg.body.push_str("\n};\n");
    }

    assemble_partitioned_module(&cg, header, mode)
}

/// Emits `blocks/<slug>.js` (or `.ts`) merging `on interact`, `on tick`, and `on break`
/// handlers for a single registered custom block into `export const component = { ... };`.
pub fn emit_block_component_module(
    handlers: &[EventHandler],
    shared: &SharedContext,
    header: Option<&AddonDirective>,
    source_file: &str,
    source_map_comments: bool,
    mode: EmitMode,
) -> String {
    let opts = CodegenOptions {
        source_file: source_file.to_string(),
        source_map_comments,
        custom_components: Vec::new(),
        bound_block_ids: Vec::new(),
    };
    let mut cg = Codegen {
        opts: &opts,
        mode,
        state_names: shared.shared_states.clone(),
        const_strings: HashMap::new(),
        shared: shared.clone(),
        used_shared_imports: BTreeSet::new(),
        local_scopes: Vec::new(),
        emit_source_lines: true,
        needs_world: false,
        needs_system: false,
        needs_equipment_slot: false,
        needs_in_helper: false,
        needs_within_helper: false,
        in_before_event: false,
        block_interact_callbacks: Vec::new(),
        block_tick_callbacks: Vec::new(),
        body: String::new(),
        indent: 0,
    };

    let mut on_interact = Vec::new();
    let mut on_tick = Vec::new();
    let mut on_break = Vec::new();
    for ev in handlers {
        match &ev.kind {
            EventKind::BlockInteract { .. } => on_interact.push(ev),
            EventKind::BlockTick { .. } => on_tick.push(ev),
            EventKind::BreakBlock { .. } => on_break.push(ev),
            _ => {}
        }
    }

    let ev_param = if mode == EmitMode::TypeScript {
        "(ev: any)"
    } else {
        "(ev)"
    };
    let mut methods = Vec::new();

    if !on_interact.is_empty() {
        let wrap = on_interact.len() > 1;
        let snippet = cg.emit_to_buffer(2, |c| {
            for ev in &on_interact {
                if let EventKind::BlockInteract { actor_var, .. } = &ev.kind {
                    if wrap {
                        c.line("{");
                        c.indent += 1;
                    }
                    c.emit_source_comment(ev.span.line);
                    c.push_scope();
                    c.bind_local(actor_var);
                    c.bind_local("block");
                    c.line(&format!("const {actor_var} = ev.player;"));
                    c.line("const block = ev.block;");
                    c.emit_block_stmts(&ev.body.stmts);
                    c.pop_scope();
                    if wrap {
                        c.indent -= 1;
                        c.line("}");
                    }
                }
            }
        });
        methods.push(format!("    onPlayerInteract{ev_param} {{\n{snippet}    }}"));
    }

    if !on_tick.is_empty() {
        let wrap = on_tick.len() > 1;
        let snippet = cg.emit_to_buffer(2, |c| {
            for ev in &on_tick {
                if let EventKind::BlockTick { .. } = &ev.kind {
                    if wrap {
                        c.line("{");
                        c.indent += 1;
                    }
                    c.emit_source_comment(ev.span.line);
                    c.push_scope();
                    c.bind_local("block");
                    c.bind_local("dimension");
                    c.line("const block = ev.block;");
                    c.line("const dimension = ev.dimension;");
                    c.emit_block_stmts(&ev.body.stmts);
                    c.pop_scope();
                    if wrap {
                        c.indent -= 1;
                        c.line("}");
                    }
                }
            }
        });
        methods.push(format!("    onTick{ev_param} {{\n{snippet}    }}"));
    }

    if !on_break.is_empty() {
        let wrap = on_break.len() > 1;
        let snippet = cg.emit_to_buffer(2, |c| {
            for ev in &on_break {
                if let EventKind::BreakBlock { actor_var, .. } = &ev.kind {
                    if wrap {
                        c.line("{");
                        c.indent += 1;
                    }
                    c.emit_source_comment(ev.span.line);
                    c.push_scope();
                    c.bind_local(actor_var);
                    c.bind_local("block");
                    c.line(&format!("const {actor_var} = ev.player;"));
                    c.line("const block = ev.block;");
                    c.emit_block_stmts(&ev.body.stmts);
                    c.pop_scope();
                    if wrap {
                        c.indent -= 1;
                        c.line("}");
                    }
                }
            }
        });
        methods.push(format!("    onPlayerBreak{ev_param} {{\n{snippet}    }}"));
    }

    if methods.is_empty() {
        cg.line("export const component = {};");
    } else {
        cg.line("export const component = {");
        cg.body.push_str(&methods.join(",\n"));
        cg.body.push_str("\n};\n");
    }

    assemble_partitioned_module(&cg, header, mode)
}

/// Emits `world/<stem>.js` (or `.ts`) containing global events, timers,
/// unbound item/block listeners, and cancellable block/item beforeEvents.
pub fn emit_world_module(
    world_items: &[TopLevelItem],
    shared: &SharedContext,
    header: Option<&AddonDirective>,
    source_file: &str,
    source_map_comments: bool,
    mode: EmitMode,
) -> String {
    let opts = CodegenOptions {
        source_file: source_file.to_string(),
        source_map_comments,
        custom_components: Vec::new(),
        bound_block_ids: Vec::new(),
    };
    let mut cg = Codegen {
        opts: &opts,
        mode,
        state_names: shared.shared_states.clone(),
        const_strings: HashMap::new(),
        shared: shared.clone(),
        used_shared_imports: BTreeSet::new(),
        local_scopes: Vec::new(),
        emit_source_lines: true,
        needs_world: false,
        needs_system: false,
        needs_equipment_slot: false,
        needs_in_helper: false,
        needs_within_helper: false,
        in_before_event: false,
        block_interact_callbacks: Vec::new(),
        block_tick_callbacks: Vec::new(),
        body: String::new(),
        indent: 0,
    };

    for (idx, item) in world_items.iter().enumerate() {
        if idx > 0 {
            cg.body.push('\n');
        }
        let line = match item {
            TopLevelItem::EventHandler(ev) => ev.span.line,
            TopLevelItem::AfterTimer { span, .. } | TopLevelItem::EveryTimer { span, .. } => {
                span.line
            }
            _ => 0,
        };
        cg.emit_source_comment(line);
        cg.emit_top_level(item);
    }

    assemble_partitioned_module(&cg, header, mode)
}

struct Codegen<'a> {
    opts: &'a CodegenOptions,
    mode: EmitMode,
    state_names: HashSet<String>,
    const_strings: HashMap<String, String>,
    shared: SharedContext,
    used_shared_imports: BTreeSet<String>,
    local_scopes: Vec<HashSet<String>>,
    emit_source_lines: bool,
    needs_world: bool,
    needs_system: bool,
    needs_equipment_slot: bool,
    needs_in_helper: bool,
    needs_within_helper: bool,
    in_before_event: bool,
    block_interact_callbacks: Vec<String>,
    block_tick_callbacks: Vec<String>,
    body: String,
    indent: usize,
}

impl<'a> Codegen<'a> {
    fn push_scope(&mut self) {
        self.local_scopes.push(HashSet::new());
    }

    fn pop_scope(&mut self) {
        self.local_scopes.pop();
    }

    fn bind_local(&mut self, name: &str) {
        if let Some(top) = self.local_scopes.last_mut() {
            top.insert(name.to_string());
        }
    }

    fn is_local(&self, name: &str) -> bool {
        self.local_scopes.iter().rev().any(|s| s.contains(name))
    }

    fn emit_source_comment(&mut self, line: usize) {
        if self.emit_source_lines && self.opts.source_map_comments && line > 0 {
            self.line(&format!("// @pstdr-source: {}:{line}", self.opts.source_file));
        }
    }
    fn is_bound_block(&self, block_id: &Expr) -> bool {
        let has_block_comp = self
            .opts
            .custom_components
            .iter()
            .any(|(_, k)| *k == ComponentKind::Block);
        if !has_block_comp {
            return false;
        }
        if self.opts.bound_block_ids.is_empty() {
            return true;
        }
        if let Some(id_str) = eval_static_string(block_id, &self.const_strings) {
            self.opts.bound_block_ids.contains(&id_str)
        } else {
            false
        }
    }

    fn emit_to_buffer(&mut self, indent: usize, f: impl FnOnce(&mut Self)) -> String {
        let prev_body = std::mem::take(&mut self.body);
        let prev_indent = self.indent;
        self.indent = indent;
        f(self);
        let captured = std::mem::replace(&mut self.body, prev_body);
        self.indent = prev_indent;
        captured
    }

    fn push_indent(&mut self) {
        for _ in 0..self.indent {
            self.body.push_str("    ");
        }
    }

    fn line(&mut self, s: &str) {
        self.push_indent();
        self.body.push_str(s);
        self.body.push('\n');
    }

    fn emit_program(&mut self, program: &Program) {
        for item in &program.items {
            let before_len = self.body.len();
            let had_content = before_len > 0;
            if had_content {
                self.body.push('\n');
            }
            let after_sep_len = self.body.len();
            self.emit_top_level(item);
            if had_content && self.body.len() == after_sep_len {
                self.body.truncate(before_len);
            }
        }
    }

    fn emit_top_level(&mut self, item: &TopLevelItem) {
        match item {
            TopLevelItem::ConstDecl(d) => {
                let val = self.emit_expr(&d.value);
                self.line(&format!("const {} = {val};", d.name));
            }
            TopLevelItem::MutDecl(d) => {
                let val = self.emit_expr(&d.value);
                self.line(&format!("let {} = {val};", d.name));
            }
            TopLevelItem::StateDecl(s) => {
                let default_js = self.emit_expr(&s.default_value);
                let key = format!("pstdr:{}", s.name);
                if self.mode == EmitMode::TypeScript {
                    self.line(&format!(
                        "function __get_{}(owner: any) {{ const v = owner.getDynamicProperty(\"{key}\"); return v !== undefined ? v : ({default_js}); }}",
                        s.name
                    ));
                    self.line(&format!(
                        "function __set_{}(owner: any, value: any): void {{ owner.setDynamicProperty(\"{key}\", value); }}",
                        s.name
                    ));
                } else {
                    self.line(&format!(
                        "function __get_{}(owner) {{ const v = owner.getDynamicProperty(\"{key}\"); return v !== undefined ? v : ({default_js}); }}",
                        s.name
                    ));
                    self.line(&format!(
                        "function __set_{}(owner, value) {{ owner.setDynamicProperty(\"{key}\", value); }}",
                        s.name
                    ));
                }
            }
            TopLevelItem::FuncDecl(f) => {
                let params: Vec<String> = f
                    .params
                    .iter()
                    .map(|(p, _)| {
                        if self.mode == EmitMode::TypeScript {
                            format!("{p}: any")
                        } else {
                            p.clone()
                        }
                    })
                    .collect();
                self.line(&format!("function {}({}) {{", f.name, params.join(", ")));
                self.push_scope();
                for (p, _) in &f.params {
                    self.bind_local(p);
                }
                self.indent += 1;
                self.emit_block_stmts(&f.body.stmts);
                self.indent -= 1;
                self.pop_scope();
                self.line("}");
            }
            TopLevelItem::UnsafeFuncDecl(f) => {
                self.line(&format!(
                    "// [unsafe:{} @ {}:{}]",
                    f.name, self.opts.source_file, f.span.line
                ));
                let params: Vec<String> = f
                    .params
                    .iter()
                    .map(|p| {
                        if self.mode == EmitMode::TypeScript {
                            format!("{p}: any")
                        } else {
                            p.clone()
                        }
                    })
                    .collect();
                self.line(&format!(
                    "function {}({}) {{{}}}",
                    f.name,
                    params.join(", "),
                    f.raw_body
                ));
            }
            TopLevelItem::UnsafeVarDecl(u) => {
                self.line(&format!(
                    "// [unsafe:{} @ {}:{}]",
                    u.name, self.opts.source_file, u.span.line
                ));
                let mut rest = u.raw_rest.trim_end().to_string();
                if !rest.ends_with(';') {
                    rest.push(';');
                }
                self.line(&format!("{} {}", u.keyword, rest));
            }
            TopLevelItem::EventHandler(ev) => {
                self.emit_event_handler(ev);
            }
            TopLevelItem::AfterTimer { duration, body, .. } => {
                self.needs_system = true;
                let ticks = duration.ticks_rounded();
                self.line("system.runTimeout(() => {");
                self.indent += 1;
                self.emit_block_stmts(&body.stmts);
                self.indent -= 1;
                self.line(&format!("}}, {ticks});"));
            }
            TopLevelItem::EveryTimer { duration, body, .. } => {
                self.needs_system = true;
                let ticks = duration.ticks_rounded();
                self.line("system.runInterval(() => {");
                self.indent += 1;
                self.emit_block_stmts(&body.stmts);
                self.indent -= 1;
                self.line(&format!("}}, {ticks});"));
            }
        }
    }

    fn emit_event_handler(&mut self, ev: &EventHandler) {
        let has_cancel = block_contains_cancel(&ev.body);
        let ev_param = if self.mode == EmitMode::TypeScript {
            "(ev: any)"
        } else {
            "(ev)"
        };

        match &ev.kind {
            EventKind::RightClick { item, actor_var } => {
                self.needs_world = true;
                let item_js = self.emit_expr(item);
                let bus = if has_cancel {
                    "world.beforeEvents.itemUse"
                } else {
                    "world.afterEvents.itemUse"
                };
                self.line(&format!("{bus}.subscribe({ev_param} => {{"));
                self.indent += 1;
                self.line(&format!("const {actor_var} = ev.source;"));
                self.line(&format!(
                    "if (!ev.itemStack || ev.itemStack.typeId !== ({item_js})) return;"
                ));
                let prev = self.in_before_event;
                self.in_before_event = has_cancel;
                self.emit_block_stmts(&ev.body.stmts);
                self.in_before_event = prev;
                self.indent -= 1;
                self.line("});");
            }
            EventKind::HitTarget {
                target_var,
                item,
                actor_var,
            } => {
                self.needs_world = true;
                self.needs_equipment_slot = true;
                let item_js = self.emit_expr(item);
                self.line(&format!(
                    "world.afterEvents.entityHitEntity.subscribe({ev_param} => {{"
                ));
                self.indent += 1;
                self.line("if (ev.damagingEntity.typeId !== \"minecraft:player\") return;");
                self.line(&format!("const {actor_var} = ev.damagingEntity;"));
                self.line(&format!("const {target_var} = ev.hitEntity;"));
                self.line(&format!(
                    "const __held = {actor_var}.getComponent(\"minecraft:equippable\")?.getEquipment(EquipmentSlot.Mainhand);"
                ));
                self.line(&format!(
                    "if (!__held || __held.typeId !== ({item_js})) return;"
                ));
                self.emit_block_stmts(&ev.body.stmts);
                self.indent -= 1;
                self.line("});");
            }
            EventKind::BreakBlock {
                block_id,
                actor_var,
            } => {
                self.needs_world = true;
                let block_js = self.emit_expr(block_id);
                if has_cancel {
                    self.line(&format!(
                        "world.beforeEvents.playerBreakBlock.subscribe({ev_param} => {{"
                    ));
                    self.indent += 1;
                    self.line(&format!("const {actor_var} = ev.player;"));
                    self.line("const block = ev.block;");
                    self.line(&format!("if (ev.block.typeId !== ({block_js})) return;"));
                    let prev = self.in_before_event;
                    self.in_before_event = true;
                    self.emit_block_stmts(&ev.body.stmts);
                    self.in_before_event = prev;
                    self.indent -= 1;
                    self.line("});");
                } else {
                    self.line(&format!(
                        "world.afterEvents.playerBreakBlock.subscribe({ev_param} => {{"
                    ));
                    self.indent += 1;
                    self.line(&format!("const {actor_var} = ev.player;"));
                    self.line("const block = ev.block;");
                    self.line(&format!(
                        "if (ev.brokenBlockPermutation.type.id !== ({block_js})) return;"
                    ));
                    self.emit_block_stmts(&ev.body.stmts);
                    self.indent -= 1;
                    self.line("});");
                }
            }
            EventKind::PlayerJoin { actor_var } => {
                self.needs_world = true;
                self.line(&format!(
                    "world.afterEvents.playerSpawn.subscribe({ev_param} => {{"
                ));
                self.indent += 1;
                self.line("if (!ev.initialSpawn) return;");
                self.line(&format!("const {actor_var} = ev.player;"));
                self.emit_block_stmts(&ev.body.stmts);
                self.indent -= 1;
                self.line("});");
            }
            EventKind::Hurt {
                target_var,
                attacker_var,
            } => {
                self.needs_world = true;
                self.line(&format!(
                    "world.afterEvents.entityHurt.subscribe({ev_param} => {{"
                ));
                self.indent += 1;
                self.line(&format!("const {target_var} = ev.hurtEntity;"));
                if let Some(a) = attacker_var {
                    self.line(&format!("const {a} = ev.damageSource?.damagingEntity;"));
                }
                self.emit_block_stmts(&ev.body.stmts);
                self.indent -= 1;
                self.line("});");
            }
            EventKind::Die {
                target_var,
                killer_var,
            } => {
                self.needs_world = true;
                self.line(&format!(
                    "world.afterEvents.entityDie.subscribe({ev_param} => {{"
                ));
                self.indent += 1;
                self.line(&format!("const {target_var} = ev.deadEntity;"));
                if let Some(k) = killer_var {
                    self.line(&format!("const {k} = ev.damageSource?.damagingEntity;"));
                }
                self.emit_block_stmts(&ev.body.stmts);
                self.indent -= 1;
                self.line("});");
            }
            EventKind::Consume { item, actor_var } => {
                self.needs_world = true;
                let item_js = self.emit_expr(item);
                self.line(&format!(
                    "world.afterEvents.itemCompleteUse.subscribe({ev_param} => {{"
                ));
                self.indent += 1;
                self.line(&format!("const {actor_var} = ev.source;"));
                self.line(&format!(
                    "if (!ev.itemStack || ev.itemStack.typeId !== ({item_js})) return;"
                ));
                self.emit_block_stmts(&ev.body.stmts);
                self.indent -= 1;
                self.line("});");
            }
            EventKind::BlockInteract {
                block_id,
                actor_var,
            } => {
                if self.is_bound_block(block_id) && !has_cancel {
                    let snippet = self.emit_to_buffer(3, |cg| {
                        cg.line(&format!("const {actor_var} = ev.player;"));
                        cg.line("const block = ev.block;");
                        cg.emit_block_stmts(&ev.body.stmts);
                    });
                    self.block_interact_callbacks.push(snippet);
                } else {
                    self.needs_world = true;
                    let block_js = self.emit_expr(block_id);
                    let bus = if has_cancel {
                        "world.beforeEvents.playerInteractWithBlock"
                    } else {
                        "world.afterEvents.playerInteractWithBlock"
                    };
                    self.line(&format!("{bus}.subscribe({ev_param} => {{"));
                    self.indent += 1;
                    self.line(&format!("const {actor_var} = ev.player;"));
                    self.line("const block = ev.block;");
                    self.line(&format!("if (ev.block.typeId !== ({block_js})) return;"));
                    let prev = self.in_before_event;
                    self.in_before_event = has_cancel;
                    self.emit_block_stmts(&ev.body.stmts);
                    self.in_before_event = prev;
                    self.indent -= 1;
                    self.line("});");
                }
            }
            EventKind::BlockTick { .. } => {
                let snippet = self.emit_to_buffer(3, |cg| {
                    cg.line("const block = ev.block;");
                    cg.line("const dimension = ev.dimension;");
                    cg.emit_block_stmts(&ev.body.stmts);
                });
                self.block_tick_callbacks.push(snippet);
            }
            EventKind::ProjectileHit {
                target_var,
                projectile_id,
                shooter_var,
            } => {
                self.needs_world = true;
                self.line(&format!(
                    "world.afterEvents.projectileHitEntity.subscribe({ev_param} => {{"
                ));
                self.indent += 1;
                self.line(&format!("const {target_var} = ev.getEntityHit()?.entity;"));
                self.line(&format!("if (!{target_var}) return;"));
                if let Some(proj) = projectile_id {
                    let proj_js = self.emit_expr(proj);
                    self.line(&format!(
                        "if (!ev.projectile || ev.projectile.typeId !== ({proj_js})) return;"
                    ));
                }
                if let Some(shooter) = shooter_var {
                    self.line(&format!("const {shooter} = ev.source;"));
                }
                if target_var != "projectile"
                    && shooter_var.as_deref() != Some("projectile")
                    && block_references_ident(&ev.body, "projectile")
                {
                    self.line("const projectile = ev.projectile;");
                }
                self.emit_block_stmts(&ev.body.stmts);
                self.indent -= 1;
                self.line("});");
            }
            EventKind::EntitySpawn {
                entity_var,
                entity_type,
            } => {
                self.needs_world = true;
                self.line(&format!(
                    "world.afterEvents.entitySpawn.subscribe({ev_param} => {{"
                ));
                self.indent += 1;
                self.line(&format!("const {entity_var} = ev.entity;"));
                if let Some(ty) = entity_type {
                    let ty_js = self.emit_expr(ty);
                    self.line(&format!("if ({entity_var}.typeId !== ({ty_js})) return;"));
                }
                self.emit_block_stmts(&ev.body.stmts);
                self.indent -= 1;
                self.line("});");
            }
        }
    }

    fn emit_block_stmts(&mut self, stmts: &[Stmt]) {
        for stmt in stmts {
            self.emit_stmt(stmt);
        }
    }

    fn wrap_before_event_mutation(&mut self, action_line: String) {
        if self.in_before_event {
            self.needs_system = true;
            self.line("system.run(() => {");
            self.indent += 1;
            self.line(&action_line);
            self.indent -= 1;
            self.line("});");
        } else {
            self.line(&action_line);
        }
    }

    fn emit_stmt(&mut self, stmt: &Stmt) {
        match stmt {
            Stmt::ConstDecl(d) => {
                let val = self.emit_expr(&d.value);
                self.bind_local(&d.name);
                self.line(&format!("const {} = {val};", d.name));
            }
            Stmt::MutDecl(d) => {
                let val = self.emit_expr(&d.value);
                self.bind_local(&d.name);
                self.line(&format!("let {} = {val};", d.name));
            }
            Stmt::Assign {
                target, op, value, ..
            } => {
                let val_js = self.emit_expr(value);
                match target {
                    AssignTarget::Ident(name, _) => {
                        if !self.is_local(name) && self.shared.shared_muts.contains(name) {
                            if self.shared.shared_import_path.is_some() {
                                self.used_shared_imports.insert("__pstdr_mut".to_string());
                            }
                            self.line(&format!("__pstdr_mut.{name} {} {val_js};", op.as_str()));
                        } else {
                            self.line(&format!("{name} {} {val_js};", op.as_str()));
                        }
                    }
                    AssignTarget::Index { object, index, .. } => {
                        let idx_js = self.emit_expr(index);
                        if let Expr::Ident(name, _) = object {
                            if self.state_names.contains(name) {
                                if self.shared.shared_states.contains(name)
                                    && self.shared.shared_import_path.is_some()
                                {
                                    self.used_shared_imports.insert(format!("__set_{name}"));
                                    if *op != AssignOp::Assign {
                                        self.used_shared_imports.insert(format!("__get_{name}"));
                                    }
                                }
                                let line = match op {
                                    AssignOp::Assign => {
                                        format!("__set_{name}({idx_js}, {val_js});")
                                    }
                                    AssignOp::AddAssign => format!(
                                        "__set_{name}({idx_js}, __get_{name}({idx_js}) + ({val_js}));"
                                    ),
                                    AssignOp::SubAssign => format!(
                                        "__set_{name}({idx_js}, __get_{name}({idx_js}) - ({val_js}));"
                                    ),
                                    AssignOp::MulAssign => format!(
                                        "__set_{name}({idx_js}, __get_{name}({idx_js}) * ({val_js}));"
                                    ),
                                    AssignOp::DivAssign => format!(
                                        "__set_{name}({idx_js}, __get_{name}({idx_js}) / ({val_js}));"
                                    ),
                                };
                                self.wrap_before_event_mutation(line);
                                return;
                            }
                        }
                        let obj_js = self.emit_expr(object);
                        self.line(&format!("{obj_js}[{idx_js}] {} {val_js};", op.as_str()));
                    }
                    AssignTarget::Field { object, field, .. } => {
                        let obj_js = self.emit_expr(object);
                        let mapped = map_property(field).unwrap_or(field.as_str());
                        self.line(&format!("{obj_js}.{mapped} {} {val_js};", op.as_str()));
                    }
                }
            }
            Stmt::If {
                condition,
                then_block,
                else_branch,
                ..
            } => {
                let cond_js = self.emit_expr(condition);
                self.line(&format!("if ({cond_js}) {{"));
                self.push_scope();
                self.indent += 1;
                self.emit_block_stmts(&then_block.stmts);
                self.indent -= 1;
                self.pop_scope();
                match else_branch {
                    None => self.line("}"),
                    Some(ElseBranch::Else(b)) => {
                        self.line("} else {");
                        self.push_scope();
                        self.indent += 1;
                        self.emit_block_stmts(&b.stmts);
                        self.indent -= 1;
                        self.pop_scope();
                        self.line("}");
                    }
                    Some(ElseBranch::ElseIf(next_if)) => {
                        self.push_indent();
                        self.body.push_str("} else ");
                        self.emit_if_inline(next_if);
                    }
                }
            }
            Stmt::For {
                var, iter, body, ..
            } => {
                let iter_js = self.emit_expr(iter);
                self.line(&format!("for (const {var} of {iter_js}) {{"));
                self.push_scope();
                self.bind_local(var);
                self.indent += 1;
                self.emit_block_stmts(&body.stmts);
                self.indent -= 1;
                self.pop_scope();
                self.line("}");
            }
            Stmt::While {
                condition, body, ..
            } => {
                let cond_js = self.emit_expr(condition);
                self.line(&format!("while ({cond_js}) {{"));
                self.push_scope();
                self.indent += 1;
                self.emit_block_stmts(&body.stmts);
                self.indent -= 1;
                self.pop_scope();
                self.line("}");
            }
            Stmt::Return { value, .. } => match value {
                Some(v) => {
                    let v_js = self.emit_expr(v);
                    self.line(&format!("return {v_js};"));
                }
                None => self.line("return;"),
            },
            Stmt::CancelEvent { .. } => {
                self.line("ev.cancel = true;");
            }
            Stmt::Damage { target, amount, .. } => {
                let t = self.emit_expr(target);
                let a = self.emit_expr(amount);
                self.wrap_before_event_mutation(format!("{t}.applyDamage({a});"));
            }
            Stmt::Ignite {
                target, duration, ..
            } => {
                let t = self.emit_expr(target);
                let secs = format_number(duration.seconds_f64());
                self.wrap_before_event_mutation(format!("{t}.setOnFire({secs}, true);"));
            }
            Stmt::ApplyEffect {
                effect,
                level,
                target,
                duration,
                ..
            } => {
                let t = self.emit_expr(target);
                let ticks = duration.ticks_rounded();
                let amp = match level {
                    Expr::Number(n, _) if n.fract() == 0.0 => format!("{}", (*n as i64) - 1),
                    _ => format!("({}) - 1", self.emit_expr(level)),
                };
                self.wrap_before_event_mutation(format!(
                    "{t}.addEffect(\"{effect}\", {ticks}, {{ amplifier: {amp} }});"
                ));
            }
            Stmt::SendMessage {
                message, target, ..
            } => {
                let t = self.emit_expr(target);
                let m = self.emit_expr(message);
                self.wrap_before_event_mutation(format!("{t}.sendMessage({m});"));
            }
            Stmt::SpawnParticle {
                particle,
                location,
                dimension,
                ..
            } => {
                let p = self.emit_expr(particle);
                let call = if let Some(dim) = dimension {
                    let d = self.emit_expr(dim);
                    if matches!(location, Expr::Ident(_, _)) {
                        let e = self.emit_expr(location);
                        format!("{d}.spawnParticle({p}, {e}.location);")
                    } else {
                        let l = self.emit_expr(location);
                        format!("{d}.spawnParticle({p}, {l});")
                    }
                } else if let Expr::Member { object, field, .. } = location {
                    if field == "location" || field == "head_location" {
                        let obj_js = self.emit_expr(object);
                        let loc_js = self.emit_expr(location);
                        format!("{obj_js}.dimension.spawnParticle({p}, {loc_js});")
                    } else {
                        self.needs_world = true;
                        let l = self.emit_expr(location);
                        format!("world.getDimension(\"overworld\").spawnParticle({p}, {l});")
                    }
                } else if matches!(location, Expr::Ident(_, _)) {
                    let e = self.emit_expr(location);
                    format!("{e}.dimension.spawnParticle({p}, {e}.location);")
                } else {
                    self.needs_world = true;
                    let l = self.emit_expr(location);
                    format!("world.getDimension(\"overworld\").spawnParticle({p}, {l});")
                };
                self.wrap_before_event_mutation(call);
            }
            Stmt::After { duration, body, .. } => {
                self.needs_system = true;
                let ticks = duration.ticks_rounded();
                let prev = self.in_before_event;
                self.in_before_event = false;
                self.line("system.runTimeout(() => {");
                self.indent += 1;
                self.emit_block_stmts(&body.stmts);
                self.indent -= 1;
                self.line(&format!("}}, {ticks});"));
                self.in_before_event = prev;
            }
            Stmt::Every { duration, body, .. } => {
                self.needs_system = true;
                let ticks = duration.ticks_rounded();
                let prev = self.in_before_event;
                self.in_before_event = false;
                self.line("system.runInterval(() => {");
                self.indent += 1;
                self.emit_block_stmts(&body.stmts);
                self.indent -= 1;
                self.line(&format!("}}, {ticks});"));
                self.in_before_event = prev;
            }
            Stmt::ExprStmt { expr, .. } => {
                let js = self.emit_expr(expr);
                self.wrap_before_event_mutation(format!("{js};"));
            }
        }
    }

    fn emit_if_inline(&mut self, stmt: &Stmt) {
        if let Stmt::If {
            condition,
            then_block,
            else_branch,
            ..
        } = stmt
        {
            let cond_js = self.emit_expr(condition);
            self.body.push_str(&format!("if ({cond_js}) {{\n"));
            self.indent += 1;
            self.emit_block_stmts(&then_block.stmts);
            self.indent -= 1;
            match else_branch {
                None => self.line("}"),
                Some(ElseBranch::Else(b)) => {
                    self.line("} else {");
                    self.indent += 1;
                    self.emit_block_stmts(&b.stmts);
                    self.indent -= 1;
                    self.line("}");
                }
                Some(ElseBranch::ElseIf(next_if)) => {
                    self.push_indent();
                    self.body.push_str("} else ");
                    self.emit_if_inline(next_if);
                }
            }
        }
    }

    fn emit_expr(&mut self, expr: &Expr) -> String {
        match expr {
            Expr::Number(n, _) => format_number(*n),
            Expr::Bool(b, _) => b.to_string(),
            Expr::Null(_) => "null".to_string(),
            Expr::Duration(d) => format!("{}", d.ticks_rounded()),
            Expr::Distance(b, _) => format_number(*b),
            Expr::Ident(name, _) => {
                if name == "world" {
                    self.needs_world = true;
                } else if name == "system" {
                    self.needs_system = true;
                }
                if !self.is_local(name) {
                    if self.shared.shared_muts.contains(name) {
                        if self.shared.shared_import_path.is_some() {
                            self.used_shared_imports.insert("__pstdr_mut".to_string());
                        }
                        return format!("__pstdr_mut.{name}");
                    }
                    if self.shared.shared_exports.contains(name)
                        && self.shared.shared_import_path.is_some()
                    {
                        self.used_shared_imports.insert(name.clone());
                    }
                }
                name.clone()
            }
            Expr::StringParts(parts, _) => {
                if parts.len() == 1 {
                    if let StringPart::Literal(s) = &parts[0] {
                        return format!("\"{}\"", escape_double_quoted(s));
                    }
                }
                let mut out = String::from("`");
                for p in parts {
                    match p {
                        StringPart::Literal(s) => out.push_str(&escape_template_literal(s)),
                        StringPart::Expr(e) => {
                            let inner = self.emit_expr(e);
                            out.push_str(&format!("${{{inner}}}"));
                        }
                    }
                }
                out.push('`');
                out
            }
            Expr::Object(fields, _) => {
                if fields.is_empty() {
                    return "{}".to_string();
                }
                let parts: Vec<String> = fields
                    .iter()
                    .map(|f| {
                        let k = if f.key_is_string {
                            format!("\"{}\"", escape_double_quoted(&f.key))
                        } else {
                            f.key.clone()
                        };
                        format!("{k}: {}", self.emit_expr(&f.value))
                    })
                    .collect();
                format!("{{ {} }}", parts.join(", "))
            }
            Expr::Array(items, _) => {
                let parts: Vec<String> = items.iter().map(|i| self.emit_expr(i)).collect();
                format!("[{}]", parts.join(", "))
            }
            Expr::Index { object, index, .. } => {
                let idx_js = self.emit_expr(index);
                if let Expr::Ident(name, _) = object.as_ref() {
                    if self.state_names.contains(name) {
                        if self.shared.shared_states.contains(name)
                            && self.shared.shared_import_path.is_some()
                        {
                            self.used_shared_imports.insert(format!("__get_{name}"));
                        }
                        return format!("__get_{name}({idx_js})");
                    }
                }
                let obj_js = self.emit_expr(object);
                format!("{obj_js}[{idx_js}]")
            }
            Expr::Member {
                object,
                field,
                optional,
                ..
            } => {
                let obj_js = self.emit_expr(object);
                let sep = if *optional { "?." } else { "." };
                let is_item_like = matches!(
                    object.as_ref(),
                    Expr::Member { field: parent_f, .. } if parent_f == "mainhand" || parent_f == "holding"
                );
                let mapped = if is_item_like {
                    map_item_property(field).unwrap_or(field.as_str())
                } else {
                    if field == "holding" || field == "mainhand" {
                        self.needs_equipment_slot = true;
                    }
                    map_property(field).unwrap_or(field.as_str())
                };
                format!("{obj_js}{sep}{mapped}")
            }
            Expr::Call { callee, args, .. } => {
                let args_js: Vec<String> = args.iter().map(|a| self.emit_expr(a)).collect();
                if let Expr::Member {
                    object,
                    field,
                    optional,
                    ..
                } = callee.as_ref()
                {
                    let obj_js = self.emit_expr(object);
                    if field == "holding" && args_js.len() == 1 {
                        self.needs_equipment_slot = true;
                        return format!(
                            "({obj_js}.getComponent(\"minecraft:equippable\")?.getEquipment(EquipmentSlot.Mainhand)?.typeId === ({}))",
                            args_js[0]
                        );
                    }
                    let sep = if *optional { "?." } else { "." };
                    let mapped_method = if matches!(object.as_ref(), Expr::Ident(w, _) if w == "world")
                    {
                        map_world_method(field).or_else(|| map_method(field))
                    } else {
                        map_method(field)
                    }
                    .unwrap_or(field.as_str());
                    return format!("{obj_js}{sep}{mapped_method}({})", args_js.join(", "));
                }
                let callee_js = self.emit_expr(callee);
                format!("{callee_js}({})", args_js.join(", "))
            }
            Expr::Unary { op, expr, .. } => {
                let inner = self.emit_expr(expr);
                match op {
                    UnaryOp::Not => format!("!{inner}"),
                    UnaryOp::Neg => format!("-{inner}"),
                }
            }
            Expr::Binary {
                left, op, right, ..
            } => {
                let l = self.emit_expr(left);
                let r = self.emit_expr(right);
                match op {
                    BinaryOp::Add => format!("{l} + {r}"),
                    BinaryOp::Sub => format!("{l} - {r}"),
                    BinaryOp::Mul => format!("{l} * {r}"),
                    BinaryOp::Div => format!("{l} / {r}"),
                    BinaryOp::Mod => format!("{l} % {r}"),
                    BinaryOp::Eq => {
                        if matches!(left.as_ref(), Expr::Null(_))
                            || matches!(right.as_ref(), Expr::Null(_))
                        {
                            format!("{l} == {r}")
                        } else {
                            format!("{l} === {r}")
                        }
                    }
                    BinaryOp::Neq => {
                        if matches!(left.as_ref(), Expr::Null(_))
                            || matches!(right.as_ref(), Expr::Null(_))
                        {
                            format!("{l} != {r}")
                        } else {
                            format!("{l} !== {r}")
                        }
                    }
                    BinaryOp::Lt => format!("{l} < {r}"),
                    BinaryOp::Le => format!("{l} <= {r}"),
                    BinaryOp::Gt => format!("{l} > {r}"),
                    BinaryOp::Ge => format!("{l} >= {r}"),
                    BinaryOp::And => format!("{l} && {r}"),
                    BinaryOp::Or => format!("{l} || {r}"),
                    BinaryOp::Nullish => format!("{l} ?? {r}"),
                    BinaryOp::In => {
                        self.needs_in_helper = true;
                        format!("__pstdr_in({l}, {r})")
                    }
                    BinaryOp::Within => {
                        self.needs_within_helper = true;
                        format!("__pstdr_within({l}, {r})")
                    }
                }
            }
            Expr::IsCheck {
                subject,
                negated,
                predicate,
                ..
            } => {
                let subj = self.emit_expr(subject);
                let check = match predicate {
                    IsPredicate::Sneaking => format!("{subj}.isSneaking"),
                    IsPredicate::Sprinting => format!("{subj}.isSprinting"),
                    IsPredicate::Swimming => format!("{subj}.isSwimming"),
                    IsPredicate::Flying => format!("{subj}.isFlying"),
                    IsPredicate::Sleeping => format!("{subj}.isSleeping"),
                    IsPredicate::OnGround => format!("{subj}.isOnGround"),
                    IsPredicate::InWater => format!("{subj}.isInWater"),
                    IsPredicate::Holding(item) => {
                        self.needs_equipment_slot = true;
                        let item_js = self.emit_expr(item);
                        format!(
                            "({subj}.getComponent(\"minecraft:equippable\")?.getEquipment(EquipmentSlot.Mainhand)?.typeId === ({item_js}))"
                        )
                    }
                };
                if *negated {
                    format!("!({check})")
                } else {
                    check
                }
            }
            Expr::Ternary {
                cond,
                then_expr,
                else_expr,
                ..
            } => {
                format!(
                    "{} ? {} : {}",
                    self.emit_expr(cond),
                    self.emit_expr(then_expr),
                    self.emit_expr(else_expr)
                )
            }
            Expr::Paren(inner, _) => format!("({})", self.emit_expr(inner)),
        }
    }
}

fn block_references_ident(block: &Block, name: &str) -> bool {
    block.stmts.iter().any(|s| stmt_references_ident(s, name))
}

fn stmt_references_ident(stmt: &Stmt, name: &str) -> bool {
    match stmt {
        Stmt::ConstDecl(d) | Stmt::MutDecl(d) => expr_references_ident(&d.value, name),
        Stmt::Assign { target, value, .. } => {
            let t_ref = match target {
                AssignTarget::Ident(n, _) => n == name,
                AssignTarget::Index { object, index, .. } => {
                    expr_references_ident(object, name) || expr_references_ident(index, name)
                }
                AssignTarget::Field { object, .. } => expr_references_ident(object, name),
            };
            t_ref || expr_references_ident(value, name)
        }
        Stmt::If {
            condition,
            then_block,
            else_branch,
            ..
        } => {
            expr_references_ident(condition, name)
                || block_references_ident(then_block, name)
                || match else_branch {
                    Some(ElseBranch::Else(b)) => block_references_ident(b, name),
                    Some(ElseBranch::ElseIf(s)) => stmt_references_ident(s, name),
                    None => false,
                }
        }
        Stmt::For { iter, body, .. } => {
            expr_references_ident(iter, name) || block_references_ident(body, name)
        }
        Stmt::While {
            condition, body, ..
        } => expr_references_ident(condition, name) || block_references_ident(body, name),
        Stmt::Return { value, .. } => value
            .as_ref()
            .is_some_and(|v| expr_references_ident(v, name)),
        Stmt::CancelEvent { .. } => false,
        Stmt::Damage { target, amount, .. } => {
            expr_references_ident(target, name) || expr_references_ident(amount, name)
        }
        Stmt::Ignite { target, .. } => expr_references_ident(target, name),
        Stmt::ApplyEffect { level, target, .. } => {
            expr_references_ident(level, name) || expr_references_ident(target, name)
        }
        Stmt::SendMessage {
            message, target, ..
        } => expr_references_ident(message, name) || expr_references_ident(target, name),
        Stmt::SpawnParticle {
            particle,
            location,
            dimension,
            ..
        } => {
            expr_references_ident(particle, name)
                || expr_references_ident(location, name)
                || dimension
                    .as_ref()
                    .is_some_and(|d| expr_references_ident(d, name))
        }
        Stmt::After { body, .. } | Stmt::Every { body, .. } => block_references_ident(body, name),
        Stmt::ExprStmt { expr, .. } => expr_references_ident(expr, name),
    }
}

fn expr_references_ident(expr: &Expr, name: &str) -> bool {
    match expr {
        Expr::Ident(n, _) => n == name,
        Expr::Number(_, _)
        | Expr::Bool(_, _)
        | Expr::Null(_)
        | Expr::Duration(_)
        | Expr::Distance(_, _) => false,
        Expr::StringParts(parts, _) => parts.iter().any(|p| match p {
            StringPart::Literal(_) => false,
            StringPart::Expr(e) => expr_references_ident(e, name),
        }),
        Expr::Object(fields, _) => fields.iter().any(|f| expr_references_ident(&f.value, name)),
        Expr::Array(items, _) => items.iter().any(|i| expr_references_ident(i, name)),
        Expr::Index { object, index, .. } => {
            expr_references_ident(object, name) || expr_references_ident(index, name)
        }
        Expr::Member { object, .. } => expr_references_ident(object, name),
        Expr::Call { callee, args, .. } => {
            expr_references_ident(callee, name)
                || args.iter().any(|a| expr_references_ident(a, name))
        }
        Expr::Unary { expr: inner, .. } | Expr::Paren(inner, _) => {
            expr_references_ident(inner, name)
        }
        Expr::Binary { left, right, .. } => {
            expr_references_ident(left, name) || expr_references_ident(right, name)
        }
        Expr::IsCheck {
            subject, predicate, ..
        } => {
            expr_references_ident(subject, name)
                || match predicate {
                    IsPredicate::Holding(item) => expr_references_ident(item, name),
                    _ => false,
                }
        }
        Expr::Ternary {
            cond,
            then_expr,
            else_expr,
            ..
        } => {
            expr_references_ident(cond, name)
                || expr_references_ident(then_expr, name)
                || expr_references_ident(else_expr, name)
        }
    }
}

pub(crate) fn block_contains_cancel(block: &Block) -> bool {
    block.stmts.iter().any(stmt_contains_cancel)
}

fn stmt_contains_cancel(stmt: &Stmt) -> bool {
    match stmt {
        Stmt::CancelEvent { .. } => true,
        Stmt::If {
            then_block,
            else_branch,
            ..
        } => {
            block_contains_cancel(then_block)
                || match else_branch {
                    Some(ElseBranch::Else(b)) => block_contains_cancel(b),
                    Some(ElseBranch::ElseIf(s)) => stmt_contains_cancel(s),
                    None => false,
                }
        }
        Stmt::For { body, .. } | Stmt::While { body, .. } => block_contains_cancel(body),
        _ => false,
    }
}

fn format_number(n: f64) -> String {
    if n.fract() == 0.0 && n.abs() < 1e15 {
        format!("{}", n as i64)
    } else {
        format!("{n}")
    }
}

fn escape_double_quoted(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            other => out.push(other),
        }
    }
    out
}

fn escape_template_literal(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut prev_dollar = false;
    for c in s.chars() {
        match c {
            '\\' => {
                out.push_str("\\\\");
                prev_dollar = false;
            }
            '`' => {
                out.push_str("\\`");
                prev_dollar = false;
            }
            '$' => {
                out.push('$');
                prev_dollar = true;
            }
            '{' if prev_dollar => {
                out.pop();
                out.push_str("\\${");
                prev_dollar = false;
            }
            '\n' => {
                out.push_str("\\n");
                prev_dollar = false;
            }
            '\r' => {
                out.push_str("\\r");
                prev_dollar = false;
            }
            '\t' => {
                out.push_str("\\t");
                prev_dollar = false;
            }
            other => {
                out.push(other);
                prev_dollar = false;
            }
        }
    }
    out
}
